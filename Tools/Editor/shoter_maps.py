def build_arena(b, include_navigation):
    build_shell(b)
    build_base(b, "blue")
    build_base(b, "red")
    build_center(b)
    build_pillars(b)
    build_lane_walls(b)
    build_cover(b)
    build_catwalks(b)
    build_vents(b)
    build_gameplay(b)
    if ADD_SKYLINE:
        build_skyline(b)
    build_atmosphere(b)
    if include_navigation:
        build_navigation(b)


def build_map(name, game_mode_class, include_navigation):
    map_path = "{}/{}".format(MAP_DIR, name)
    C.log("Map {}: building from scratch".format(map_path))
    C.make_directory(MAP_DIR)
    purge_external_actor_files(map_path)

    world = new_blank_level(map_path)
    builder = MapBuilder(name)
    builder.world = world

    build_arena(builder, include_navigation)

    if world is None:
        world = _editor_world()
    mode_ok = set_game_mode(world, game_mode_class)

    if include_navigation:
        problems = validate_layout(builder.boxes, builder.points)
        for text in problems:
            C.warn("  layout: " + text)
        if not problems:
            C.log("  layout check passed: spawn clearance and nav connectivity look fine")

    saved = save_level(world, map_path)
    temp_path = "{}/_ShoterBuildTemp".format(MAP_DIR)          # only exists when the fallback level creation was used
    if saved and C.asset_exists(temp_path):
        C.delete_asset(temp_path)
    if saved:
        C.log("Map {} saved ({})".format(map_path, ", ".join("{}={}".format(k, v) for k, v in sorted(builder.counts.items()))))
    else:
        C.error("Map {} could NOT be saved".format(map_path))

    summary = builder.summary()
    summary["saved"] = bool(saved)
    summary["game_mode_set"] = bool(mode_ok)
    return summary


def run():
    """Builds Arena_Neon and MainMenu.  Returns {map name: summary dict or None, "problems": [str]}."""
    results = {}
    problems = []
    for name, game_mode, nav in ((ARENA_MAP, GAMEMODE_ARENA, True), (MENU_MAP, GAMEMODE_MENU, False)):
        try:
            info = build_map(name, game_mode, nav)
            results[name] = info
            issues = []
            if not info.get("saved"):
                issues.append("could not be saved")
            if not info.get("game_mode_set"):
                issues.append("GameMode override not set")
            if info.get("spawn_failed"):
                issues.append("{} actor(s) failed to spawn".format(info["spawn_failed"]))
            if info.get("missing_class"):
                issues.append("{} gameplay actor(s) skipped because a C++ class is missing (compile the project first)".format(info["missing_class"]))
            if issues:
                problems.append("{}: {}".format(name, "; ".join(issues)))
        except Exception:
            C.log_exception("Map {}".format(name))
            results[name] = None
            problems.append("{}: exception, see the log above".format(name))
    results["problems"] = problems
    return results
