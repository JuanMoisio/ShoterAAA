def _component(actor, component_class):
    if actor is None:
        return None
    try:
        return actor.get_component_by_class(component_class)
    except Exception:
        return None


def _exposure_range():
    low, high = EXPOSURE_BRIGHTNESS_RANGE
    try:
        extended = int(unreal.SystemLibrary.get_console_variable_int_value("r.DefaultFeature.AutoExposure.ExtendDefaultLuminanceRange"))
    except Exception:
        extended = 0
    if extended:
        convert = lambda luminance: math.log(max(luminance, 1e-6) * 8.0, 2.0)
        low, high = convert(low), convert(high)
        C.log("  auto exposure: extended luminance range active -> EV100 {:.2f} .. {:.2f}".format(low, high))
    else:
        C.log("  auto exposure: brightness {:.2f} .. {:.2f}".format(low, high))
    return low, high


