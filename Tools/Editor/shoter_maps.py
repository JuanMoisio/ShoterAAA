class MapBuilder(object):
    """Spawns actors into the current editor level and keeps a record of what it built."""

    def __init__(self, name):
        self.name = name
        self.eas = C.get_subsystem("EditorActorSubsystem")
        self.cube = None
        self._materials = {}
        self._label_counts = {}
        self.boxes = []        # dicts with the AABB of every cube actor (used by validate_layout and the offline preview)
        self.points = []       # (kind, label, x, y, z) of gameplay actors
        self.counts = {}
        self.world = None

    # ---- bookkeeping ---------------------------------------------------------------------------

    def count(self, key, amount=1):
        self.counts[key] = self.counts.get(key, 0) + amount

    def label(self, base):
        number = self._label_counts.get(base, 0) + 1
        self._label_counts[base] = number
        return "{}_{:02d}".format(base, number)

    def material(self, key):
        if key is None:
            return None
        if key not in self._materials:
            path = "{}/{}".format(MATERIAL_DIR, MATERIAL_ASSETS[key])
            asset = C.load_asset(path)
            if asset is None:
                C.warn_once(("material", path), "Material {} not found - run the materials step first (actors will use the default material)".format(path))
            self._materials[key] = asset
        return self._materials[key]

    def cube_mesh(self):
        if self.cube is None:
            self.cube = C.load_asset(CUBE_PATH)
            if self.cube is None:
                raise RuntimeError("{} could not be loaded".format(CUBE_PATH))
        return self.cube

    # ---- spawning ------------------------------------------------------------------------------

    def spawn(self, actor_class, location, rotation=None, label=None, folder=None):
        """Spawns an actor; returns None (and counts a failure) when that is impossible."""
        if actor_class is None:
            self.count("spawn_failed")
            return None
        rotation = rotation if rotation is not None else C.rot()
        actor = None
        if self.eas is not None:
            try:
                actor = self.eas.spawn_actor_from_class(actor_class, location, rotation)
            except Exception as exc:
                C.warn_once(("spawn", str(exc)[:80]), "spawn_actor_from_class({}) failed: {} (further identical failures are not logged)".format(
                    getattr(actor_class, "__name__", actor_class), exc))
        if actor is None and hasattr(unreal, "EditorLevelLibrary"):
            try:
                actor = unreal.EditorLevelLibrary.spawn_actor_from_class(actor_class, location, rotation)
            except Exception as exc:
                C.warn_once(("spawn-fallback", str(exc)[:80]), "EditorLevelLibrary.spawn_actor_from_class failed: {} (further identical failures are not logged)".format(exc))
        if actor is None:
            self.count("spawn_failed")
            return None
        if label:
            try:
                actor.set_actor_label(label)
            except Exception:
                pass
        if folder:
            try:
                actor.set_folder_path(folder)
            except Exception:
                pass
        return actor

    def box(self, label, xr, yr, zr, material, folder="Geometry", kind="solid", center=None, size=None, rotation=None):
        """
        Spawns one cube actor spanning the given axis aligned ranges (cm).  `kind` is only used by validate_layout:
        solid (blocks walking), wall, floor, trim (decoration), ramp, skyline.
        """
        if center is None:
            center = ((xr[0] + xr[1]) / 2.0, (yr[0] + yr[1]) / 2.0, (zr[0] + zr[1]) / 2.0)
            size = (abs(xr[1] - xr[0]), abs(yr[1] - yr[0]), abs(zr[1] - zr[0]))
        name = self.label(label)
        actor = self.spawn(unreal.StaticMeshActor, C.vec(*center), rotation, name, folder)
        self.boxes.append({"label": name, "kind": kind, "mat": material, "folder": folder,
                           "x": _rng(xr[0], xr[1]), "y": _rng(yr[0], yr[1]), "z": _rng(zr[0], zr[1])})
        if actor is None:
            return None
        component = getattr(actor, "static_mesh_component", None)
        if component is None:
            component = actor.get_component_by_class(unreal.StaticMeshComponent)
        try:
            component.set_static_mesh(self.cube_mesh())
            mat = self.material(material)
            if mat is not None:
                component.set_material(0, mat)
            actor.set_actor_scale3d(C.vec(size[0] / 100.0, size[1] / 100.0, size[2] / 100.0))
        except Exception:
            C.log_exception("configuring {}".format(name))
            self.count("spawn_failed")
            return None
        self.count("static_meshes")
        return actor

    def ramp(self, label, x_low, x_high, z_low, z_high, yr, thickness, material, folder, lift=0.0):
        """
        A walkable slab whose TOP surface runs from (x_low, z_low) up to (x_high, z_high) (x_high may be smaller than
        x_low: the ramp then rises toward -X).  Returns the actor.
        """
        run = abs(x_high - x_low)
        rise = z_high - z_low
        length = math.hypot(run, rise)
        angle = math.atan2(rise, run)
        direction = 1.0 if x_high >= x_low else -1.0
        normal = (-direction * math.sin(angle), math.cos(angle))              # (x, z) of the top surface normal
        mid = ((x_low + x_high) / 2.0, (z_low + z_high) / 2.0)
        offset = -thickness / 2.0 + lift
        center = (mid[0] + normal[0] * offset, (yr[0] + yr[1]) / 2.0, mid[1] + normal[1] * offset)
        size = (length, abs(yr[1] - yr[0]), thickness)
        rotation = C.rot(pitch=math.degrees(angle), yaw=0.0 if direction > 0 else 180.0)
        return self.box(label, (x_low, x_high), yr, (z_low, z_high), material, folder, kind="ramp", center=center, size=size, rotation=rotation)

    # ---- lights --------------------------------------------------------------------------------

    def _light_color(self, component, rgb):
        try:
            component.set_light_color(C.lin(rgb[0], rgb[1], rgb[2]), True)
            return
        except Exception:
            pass
        C.set_prop(component, "LightColor", C.color8(*[int(round(255.0 * max(0.0, min(1.0, v) ** (1.0 / 2.2)))) for v in rgb]))

    def _prepare_light(self, actor, component_class, rgb, intensity, shadows, units="CANDELAS"):
        component = actor.get_component_by_class(component_class)
        if component is None:
            C.warn("{} has no {}".format(actor.get_actor_label(), component_class.__name__))
            return None
        C.set_prop(component, "Mobility", unreal.ComponentMobility.MOVABLE)
        if units and hasattr(unreal, "LightUnits"):
            C.set_prop(component, "IntensityUnits", getattr(unreal.LightUnits, units))
        C.set_prop(component, "Intensity", float(intensity))
        C.set_prop(component, "CastShadows", bool(shadows))
        self._light_color(component, rgb)
        return component

    def point_light(self, label, location, color, intensity, radius, folder="Lighting/Neon", shadows=False, source_radius=6.0):
        rgb = C.NEON[color] if isinstance(color, str) else color
        actor = self.spawn(unreal.PointLight, C.vec(*location), None, self.label(label), folder)
        if actor is None:
            return None
        component = self._prepare_light(actor, unreal.PointLightComponent, rgb, intensity * LOCAL_LIGHT_SCALE, shadows)
        if component is not None:
            C.set_prop(component, "AttenuationRadius", float(radius))
            C.set_prop(component, "bUseInverseSquaredFalloff", True)
            C.set_prop(component, "SourceRadius", float(source_radius))
        self.count("point_lights")
        return actor

    def rect_light(self, label, location, pitch, yaw, color, intensity, width, height, radius, folder="Lighting/Floods", shadows=False):
        rgb = C.NEON[color] if isinstance(color, str) else color
        actor = self.spawn(unreal.RectLight, C.vec(*location), C.rot(pitch=pitch, yaw=yaw), self.label(label), folder)
        if actor is None:
            return None
        component = self._prepare_light(actor, unreal.RectLightComponent, rgb, intensity * LOCAL_LIGHT_SCALE, shadows)
        if component is not None:
            C.set_prop(component, "SourceWidth", float(width))
            C.set_prop(component, "SourceHeight", float(height))
            C.set_prop(component, "AttenuationRadius", float(radius))
            C.set_prop(component, "BarnDoorAngle", 60.0)
        self.count("rect_lights")
        return actor

    # ---- gameplay actors -----------------------------------------------------------------------

    def player_start(self, label, x, y, z, yaw, team, in_pvp, in_zombies, folder):
        cls = C.load_cpp_class("ShoterPlayerStart")
        if cls is None:
            self.count("missing_class")
            return None
        actor = self.spawn(cls, C.vec(x, y, z), C.rot(yaw=yaw), self.label(label), folder)
        if actor is None:
            return None
        C.set_prop(actor, "TeamId", int(team))
        C.set_prop(actor, "bUseInPvP", bool(in_pvp))
        C.set_prop(actor, "bUseInZombies", bool(in_zombies))
        self.points.append(("start", label, x, y, z))
        self.count("player_starts")
        return actor

    def zombie_spawn(self, label, x, y, z, yaw, min_wave=1):
        cls = C.load_cpp_class("ShoterZombieSpawnPoint")
        if cls is None:
            self.count("missing_class")
            return None
        actor = self.spawn(cls, C.vec(x, y, z), C.rot(yaw=yaw), self.label(label), "Gameplay/ZombieSpawns")
        if actor is None:
            return None
        C.set_prop(actor, "bEnabled", True)
        C.set_prop(actor, "MinWave", int(min_wave))
        self.points.append(("zombie_spawn", label, x, y, z))
        self.count("zombie_spawns")
        if min_wave > 1:
            self.count("zombie_spawns_late")
        return actor

    def buy_station(self, label, x, y, z, yaw, weapon):
        """weapon: class name without prefix (e.g. 'ShoterWeapon_Rail') or None for an ammo station."""
        cls = C.load_cpp_class("ShoterBuyStation")
        if cls is None:
            self.count("missing_class")
            return None
        actor = self.spawn(cls, C.vec(x, y, z), C.rot(yaw=yaw), self.label(label), "Gameplay/BuyStations")
        if actor is None:
            return None
        weapon_class = None
        if weapon:
            weapon_class = C.load_cpp_class(weapon)
            if weapon_class is None:
                self.count("missing_class")
        if weapon_class is not None:                  # ammo stations keep the default (None)
            C.set_prop(actor, "WeaponClass", weapon_class)
        C.set_prop(actor, "CostOverride", -1)
        key = weapon.replace("ShoterWeapon_", "") if weapon else None
        C.set_prop(actor, "PvPCooldown", float(PVP_COOLDOWN.get(key, 30.0)))
        self.points.append(("station", label, x, y, z))
        self.count("buy_stations")
        return actor

    def summary(self):
        return dict(self.counts)


