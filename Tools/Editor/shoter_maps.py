def build_base(b, team):
    """
    One team base: alcove (side walls), team floor plate, emblem, console, four cover blocks (the two mouth blocks are MID),
    a TALL slab just outside the alcove on the long axis (hides the spawners from the platform / pillar axis, both
    sides stay wide open), spawn rows, lights.
    """
    sgn = 1.0 if team == "blue" else -1.0          # +1: the alcove opens toward +X
    neon = team
    wall_key = "wall_" + team
    team_id = 0 if team == "blue" else 1
    label = team.capitalize()
    folder_start = "Gameplay/PlayerStarts/" + label

    def xr(d0, d1):
        """x range for a depth range measured from the back wall inward."""
        return _rng(sgn * (d0 - HALF_X), sgn * (d1 - HALF_X))

    def X(depth):
        return sgn * (depth - HALF_X)

    C.log("  base {}".format(label))
    b.box("Base_{}_Plate".format(label), xr(0, 750), (-1050, 1050), (0, 4), "floor_" + team, "Geometry/Bases", kind="floor")
    for y0, y1 in ((1050, 1150), (-1150, -1050)):
        b.box("Base_{}_SideWall".format(label), xr(0, 750), (y0, y1), (-200, 500), wall_key, "Geometry/Bases", kind="wall")

    emblem = [((-300, 300), (440, 450)), ((-300, 300), (150, 160)), ((-300, -290), (150, 450)), ((290, 300), (150, 450)), ((-8, 8), (160, 440))]
    for yr, zr in emblem:
        b.box("Base_{}_Emblem".format(label), xr(0, 6), yr, zr, neon, "Neon", kind="trim")

    b.box("Base_{}_Console".format(label), xr(10, 60), (-400, 400), (0, 100), "dark", "Geometry/Bases", kind="solid")
    b.box("Base_{}_ConsoleTrim".format(label), xr(10, 60), (-400, 400), (100, 106), neon, "Neon", kind="trim")

    cover(b, "Cover_{}_Mouth".format(label), xr(600, 700), (-750, -450), MID, neon)
    cover(b, "Cover_{}_Mouth".format(label), xr(600, 700), (450, 750), MID, neon)
    solid(b, "Cover_{}_MouthSlab".format(label), xr(795, 825), (-250, 250), (0, TALL), neon, "Geometry/Cover")
    cover(b, "Cover_{}_Side".format(label), xr(350, 550), (950, 1050), 120, neon)
    cover(b, "Cover_{}_Side".format(label), xr(350, 550), (-1050, -950), 120, neon)

    b.rect_light("Base_{}_Flood".format(label), (X(60), 0, 420), -15.0, 0.0 if sgn > 0 else 180.0, neon, 2000, 500, 250, 2600, "Lighting/Bases")
    for y in (-900, 900):
        b.point_light("Base_{}_Glow".format(label), (X(450), y, 260), neon, 500, 900, "Lighting/Bases")

    for depth in (190, 420):
        for y in (-600, 0, 600):
            b.player_start("Start_{}".format(label), X(depth), y, 100, 0.0 if sgn > 0 else 180.0, team_id, True, False, folder_start)


def build_center(b):
    """
    Raised platform with two ramps, 120 cm parapet with gaps, tall L-shaped corner walls, two tall slabs flanking the
    central station (it stays open to the east and west, towards the ramps), neon trim and the zombie-mode start positions.
    """
    C.log("  center platform")
    folder = "Geometry/Center"
    b.box("Platform_Body", (-600, 600), (-600, 600), (0, 190), "wall", folder, kind="solid")
    b.box("Platform_Trim", (-604, 604), (-604, 604), (130, 142), "cyan", "Neon", kind="trim")
    b.box("Platform_Top", (-600, 600), (-600, 600), (190, 200), "floor", folder, kind="solid")
    b.box("Platform_CrossX", (-450, 450), (-3, 3), (200, 201.5), "cyan", "Neon/Floor", kind="trim")
    b.box("Platform_CrossY", (-3, 3), (-450, 450), (200, 201.5), "cyan", "Neon/Floor", kind="trim")

    # Ramps: 600 cm run for 200 cm rise = 18.4 degrees (walkable limit used here: 25).
    for sgn, name in ((-1, "West"), (1, "East")):
        b.ramp("Ramp_{}".format(name), sgn * 1200.0, sgn * 600.0, 0.0, 200.0, (-300, 300), 30.0, "light", folder)
        for yr in ((-312, -300), (300, 312)):
            b.ramp("Ramp_{}_Edge".format(name), sgn * 1200.0, sgn * 600.0, 0.0, 200.0, yr, 10.0, "cyan", "Neon")

    # Parapet (120 cm) with gaps: 400 at the middle of N/S edges, 600 where the ramps arrive; the corners are taller (below).
