def _vent_frame(wall, lateral, depth, z):
    """Maps (lateral position along the wall, depth into the arena, height) to world coordinates + inward yaw."""
    if wall == "N":
        return (lateral, HALF_Y - depth, z), -90.0
    if wall == "S":
        return (lateral, -HALF_Y + depth, z), 90.0
    if wall == "W":
        return (-HALF_X + depth, lateral, z), 0.0
    return (HALF_X - depth, lateral, z), 180.0


