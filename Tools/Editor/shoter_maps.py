def build_skyline(b):
    """Dark towers with glowing bands outside the walls: a backdrop that gives the menu camera something to look at."""
    C.log("  skyline")
    rng = random.Random(7)
    palette = ["cyan", "magenta", "blue", "orange", "red"]
    placed = []
    attempts = 0
    while len(placed) < 20 and attempts < 600:
        attempts += 1
        px = rng.uniform(-9000, 9000)
        py = rng.uniform(-7500, 7500)
        if abs(px) < 4300 and abs(py) < 3500:
            continue
        width = rng.uniform(450, 900)
        depth = rng.uniform(450, 900)
        height = rng.uniform(1800, 4500)
        if any(abs(px - qx) < (width + qw) / 2.0 + 350 and abs(py - qy) < (depth + qd) / 2.0 + 350 for qx, qy, qw, qd in placed):
            continue
        placed.append((px, py, width, depth))
        xr_, yr_ = (px - width / 2.0, px + width / 2.0), (py - depth / 2.0, py + depth / 2.0)
        b.box("Tower", xr_, yr_, (-600, height), "dark", "Geometry/Skyline", kind="skyline")
        for index in range(3):
            z0 = height * (0.35 + 0.22 * index) + rng.uniform(-80, 80)
            b.box("Tower_Band", (xr_[0] - 4, xr_[1] + 4), (yr_[0] - 4, yr_[1] + 4), (z0, z0 + rng.uniform(25, 60)),
                  rng.choice(palette), "Neon/Skyline", kind="skyline")
        b.box("Tower_Cap", (xr_[0] - 4, xr_[1] + 4), (yr_[0] - 4, yr_[1] + 4), (height, height + 30), rng.choice(palette), "Neon/Skyline", kind="skyline")


